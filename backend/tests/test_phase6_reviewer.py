"""Tests for Phase 6 Reviewer Workflow — reviewer queue, review actions, and combined findings."""

from __future__ import annotations

from fastapi.testclient import TestClient


class TestPhase6ReviewerWorkflow:
    """Test reviewer queue, decision recording, transitions, and combined findings."""

    def test_reviewer_queue_empty(self, client: TestClient) -> None:
        resp = client.get("/api/reviewer/applications")
        assert resp.status_code == 200
        data = resp.json()
        assert data["total"] == 0
        assert data["items"] == []

    def test_reviewer_queue_with_flagged_application(self, client: TestClient) -> None:
        # Create application
        create_res = client.post(
            "/api/applications",
            json={
                "institution_name": "BITS Pilani",
                "application_category": "New Institution",
                "academic_year": "2025-2026",
            },
        )
        app_id = create_res.json()["id"]

        # Validate with 0 documents -> produces high severity missing document findings
        client.post(f"/api/applications/{app_id}/validate")

        # Application should appear in reviewer queue
        resp = client.get("/api/reviewer/applications")
        assert resp.status_code == 200
        data = resp.json()
        assert data["total"] >= 1
        app_ids = [item["id"] for item in data["items"]]
        assert app_id in app_ids

        # Check item structure
        item = next(it for it in data["items"] if it["id"] == app_id)
        assert item["institution_name"] == "BITS Pilani"
        assert item["requires_human_review"] is True
        assert item["critical_findings_count"] >= 0
        assert item["high_findings_count"] >= 4

    def test_reviewer_decision_workflow_lifecycle(self, client: TestClient) -> None:
        # 1. Create application
        create_res = client.post(
            "/api/applications",
            json={
                "institution_name": "Jadavpur University",
                "application_category": "New Institution",
                "academic_year": "2025-2026",
            },
        )
        app_id = create_res.json()["id"]

        # 2. Transition pending -> in_review
        rev1 = client.post(
            f"/api/applications/{app_id}/review",
            json={
                "new_status": "in_review",
                "note": "Beginning examination of land and fee documents.",
                "actor": "officer_demo_1",
            },
        )
        assert rev1.status_code == 200
        data1 = rev1.json()
        assert data1["previous_status"] == "pending"
        assert data1["new_status"] == "in_review"
        assert data1["actor"] == "officer_demo_1"

        # Verify application record reflects updated review status
        app_check = client.get(f"/api/applications/{app_id}").json()
        assert app_check["review_status"] == "in_review"
        assert app_check["review_notes"] == "Beginning examination of land and fee documents."
        assert app_check["reviewer_actor"] == "officer_demo_1"

        # 3. Transition in_review -> needs_information
        rev2 = client.post(
            f"/api/applications/{app_id}/review",
            json={
                "new_status": "needs_information",
                "note": "Building completion certificate is illegible. Re-upload requested.",
                "actor": "officer_demo_1",
            },
        )
        assert rev2.status_code == 200
        data2 = rev2.json()
        assert data2["previous_status"] == "in_review"
        assert data2["new_status"] == "needs_information"

        # 4. Transition needs_information -> in_review
        rev3 = client.post(
            f"/api/applications/{app_id}/review",
            json={
                "new_status": "in_review",
                "note": "Applicant submitted clarification. Resuming review.",
                "actor": "officer_demo_2",
            },
        )
        assert rev3.status_code == 200

        # 5. Transition in_review -> reviewed
        rev4 = client.post(
            f"/api/applications/{app_id}/review",
            json={
                "new_status": "reviewed",
                "note": "All documents verified manually. Findings cleared.",
                "actor": "officer_demo_2",
            },
        )
        assert rev4.status_code == 200
        assert rev4.json()["new_status"] == "reviewed"

        # 6. Check review history
        hist = client.get(f"/api/applications/{app_id}/review-history").json()
        assert len(hist) == 4
        # Newest action first
        assert hist[0]["new_status"] == "reviewed"
        assert hist[3]["new_status"] == "in_review"

        # 7. Check audit trail generated by reviewer actions
        audit = client.get(f"/api/applications/{app_id}/audit-trail?event_type=reviewer_action_recorded").json()
        assert audit["total"] == 4

    def test_invalid_review_status_and_transitions(self, client: TestClient) -> None:
        # Create application
        create_res = client.post(
            "/api/applications",
            json={
                "institution_name": "Manipal Academy",
                "application_category": "New Institution",
                "academic_year": "2025-2026",
            },
        )
        app_id = create_res.json()["id"]

        # 1. Invalid status value (not in enum) -> 422
        bad_val = client.post(
            f"/api/applications/{app_id}/review",
            json={
                "new_status": "automatically_approved",
                "note": "Testing invalid status",
            },
        )
        assert bad_val.status_code == 422

        # 2. Transition to current status (pending -> pending) -> 400
        same_status = client.post(
            f"/api/applications/{app_id}/review",
            json={
                "new_status": "pending",
                "note": "Cannot set to existing status",
            },
        )
        assert same_status.status_code == 400
        assert "already in 'pending'" in same_status.json()["detail"]

        # 3. Transition to reviewed
        client.post(
            f"/api/applications/{app_id}/review",
            json={"new_status": "reviewed", "note": "Marking reviewed"},
        )

        # 4. Attempting disallowed transition: reviewed -> pending directly -> 400
        invalid_trans = client.post(
            f"/api/applications/{app_id}/review",
            json={
                "new_status": "pending",
                "note": "Cannot jump directly back to pending from reviewed",
            },
        )
        assert invalid_trans.status_code == 400
        assert "Invalid review status transition" in invalid_trans.json()["detail"]

    def test_reviewer_404_for_nonexistent_application(self, client: TestClient) -> None:
        res = client.post(
            "/api/applications/nonexistent-id-999/review",
            json={"new_status": "in_review", "note": "Test note"},
        )
        assert res.status_code == 404

        res2 = client.get("/api/applications/nonexistent-id-999/combined-findings")
        assert res2.status_code == 404

        res3 = client.get("/api/applications/nonexistent-id-999/review-history")
        assert res3.status_code == 404

    def test_combined_findings_endpoint(self, client: TestClient) -> None:
        # Create app and validate
        create_res = client.post(
            "/api/applications",
            json={
                "institution_name": "Delhi Technological University",
                "application_category": "New Institution",
                "academic_year": "2025-2026",
            },
        )
        app_id = create_res.json()["id"]

        # Run validation
        client.post(f"/api/applications/{app_id}/validate")

        # Run compliance check
        client.post(f"/api/applications/{app_id}/compliance-check")

        # Fetch combined findings
        resp = client.get(f"/api/applications/{app_id}/combined-findings")
        assert resp.status_code == 200
        data = resp.json()

        # Check structure
        assert "application" in data
        assert data["application"]["institution_name"] == "Delhi Technological University"
        assert "validation_summary" in data
        assert "validation_findings" in data
        assert len(data["validation_findings"]) >= 4
        assert "compliance_summary" in data
        assert "compliance_rule_results" in data
        assert "issuer_verifications" in data
        assert "review_history" in data
        assert "recommendation" in data
        assert "disclaimer" in data
        assert "advisory" in data["disclaimer"].lower()

        # Machine findings must be preserved after review action
        orig_findings_count = len(data["validation_findings"])
        client.post(
            f"/api/applications/{app_id}/review",
            json={"new_status": "in_review", "note": "Inspecting findings"},
        )

        resp_after = client.get(f"/api/applications/{app_id}/combined-findings").json()
        assert len(resp_after["validation_findings"]) == orig_findings_count
        assert len(resp_after["review_history"]) == 1
